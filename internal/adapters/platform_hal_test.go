func TestMockCommandRunnerHAL(t *testing.T) {
	mock := adapters.NewMockCommandRunner()
	if err := mock.WriteFile("/vault/doc1.md", []byte("# Doc 1")); err != nil {
		t.Fatalf("WriteFile failed: %v", err)
	}
	if err := mock.WriteFile("/vault/sub/nested.md", []byte("# Nested")); err != nil {
		t.Fatalf("WriteFile failed: %v", err)
	}

	data, err := mock.ReadFile("/vault/doc1.md")
	if err != nil || string(data) != "# Doc 1" {
		t.Fatalf("ReadFile mismatch: %v", err)
	}

	files, err := mock.ListFiles("/vault")
	if err != nil || len(files) != 1 || files[0] != "doc1.md" {
		t.Fatalf("unexpected ListFiles: %v (%v)", files, err)
	}

	if err := mock.RemoveFile("/vault/doc1.md"); err != nil {
		t.Fatalf("RemoveFile failed: %v", err)
	}
	if _, err := mock.ReadFile("/vault/doc1.md"); err == nil {
		t.Fatalf("expected ReadFile after RemoveFile to fail")
	}

	out, err := mock.RunCommand(".", time.Second, "git", "status")
	if err != nil || out != "ok" {
		t.Fatalf("RunCommand failed: %v (%s)", err, out)
	}
	if !mock.CheckTCPPort("127.0.0.1:11434", time.Second) {
		t.Fatalf("expected mock port 11434 to be open")
	}
	models, err := mock.QueryOllamaModels("")
	if err != nil || len(models) != 2 {
		t.Fatalf("QueryOllamaModels failed: %v", err)
	}
	reply, err := mock.GenerateOllamaText("", "llama3.2:latest", "Summarize", "context")
	if err != nil || reply == "" {
		t.Fatalf("GenerateOllamaText failed: %v", err)
	}
}

func TestOSCommandRunnerHALAndLocalOllamaServer(t *testing.T) {
	osRunner := adapters.NewOSCommandRunner()
	tmpDir := t.TempDir()
	filePath := filepath.Join(tmpDir, "notes", "test.md")

	if err := osRunner.WriteFile(filePath, []byte("hello hal")); err != nil {
		t.Fatalf("OS WriteFile failed: %v", err)
	}
	got, err := osRunner.ReadFile(filePath)
	if err != nil || string(got) != "hello hal" {
		t.Fatalf("OS ReadFile failed: %v", err)
	}
	list, err := osRunner.ListFiles(filepath.Join(tmpDir, "notes"))
	if err != nil || len(list) != 1 || list[0] != "test.md" {
		t.Fatalf("OS ListFiles failed: %v (%v)", err, list)
	}
	if err := osRunner.RemoveFile(filePath); err != nil {
		t.Fatalf("OS RemoveFile failed: %v", err)
	}
	// Removing non-existent file should be idempotent
	if err := osRunner.RemoveFile(filePath); err != nil {
		t.Fatalf("OS RemoveFile idempotent failed: %v", err)
	}

	out, err := osRunner.RunCommand(tmpDir, 5*time.Second, "go", "version")
	if err != nil || out == "" {
		t.Fatalf("OS RunCommand failed: %v", err)
	}

	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatalf("Listen failed: %v", err)
	}
	addr := ln.Addr().String()
	if !osRunner.CheckTCPPort(addr, time.Second) {
		t.Fatalf("expected CheckTCPPort true for %s", addr)
	}
	_ = ln.Close()

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		switch r.URL.Path {
		case "/api/tags":
			_ = json.NewEncoder(w).Encode(map[string]any{
				"models": []map[string]string{{"name": "llama3.2:latest"}},
			})
		case "/api/generate":
			_ = json.NewEncoder(w).Encode(map[string]string{
				"response": "Generated by test server",
			})
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	defer srv.Close()

	models, err := osRunner.QueryOllamaModels(srv.URL)
	if err != nil || len(models) != 1 || models[0] != "llama3.2:latest" {
		t.Fatalf("OS QueryOllamaModels failed: %v (%v)", err, models)
	}
	gen, err := osRunner.GenerateOllamaText(srv.URL, "llama3.2:latest", "Hi", "Sys")
	if err != nil || gen != "Generated by test server" {
		t.Fatalf("OS GenerateOllamaText failed: %v (%s)", err, gen)
	}
	if _, err := osRunner.QueryOllamaModels(srv.URL + "/bad"); err == nil {
		t.Fatalf("expected 404 from QueryOllamaModels to fail")
	}
	if _, err := osRunner.GenerateOllamaText(srv.URL+"/bad", "m", "p", "s"); err == nil {
		t.Fatalf("expected 404 from GenerateOllamaText to fail")
	}
	if osRunner.CheckTCPPort("127.0.0.1:1", 50*time.Millisecond) {
		t.Fatalf("expected closed port 1 to return false")
	}
	if list, err := osRunner.ListFiles(filepath.Join(tmpDir, "missing-dir")); err != nil || list != nil {
		t.Fatalf("expected missing dir to return nil,nil: %v", err)
	}
}

